<?php
// Creates the synthetic UI-test users in sms_db_uitest only, and writes their
// credentials to .env.uitest (git-ignored). Passwords are never printed.
require_once __DIR__ . '/guard.php';
require_once __DIR__ . '/../../shared/database_config.php';

$config = csms_database_config();
$database = csms_uitest_database($config['database']);
if ($database !== CSMS_UITEST_DATABASE || !in_array($config['host'], ['localhost', '127.0.0.1'], true)) {
    fwrite(STDERR, "Refusing: DB_NAME must be exactly sms_db_uitest on localhost.\n");
    exit(1);
}
$db = csms_database_connect($config);
if ($db->query('SELECT DATABASE()')->fetch_row()[0] !== CSMS_UITEST_DATABASE) {
    fwrite(STDERR, "Refusing: connected database is not sms_db_uitest.\n");
    exit(1);
}

$roleId = static function (string $name) use ($db): ?int {
    $stmt = $db->prepare('SELECT id FROM roles WHERE name = ?');
    $stmt->bind_param('s', $name);
    $stmt->execute();
    $row = $stmt->get_result()->fetch_row();
    return $row ? (int)$row[0] : null;
};

$users = [
    'superadmin' => ['uitest.superadmin', 'super_admin', 'Super Admin'],
    'admin' => ['uitest.admin', 'admin', 'Admin'],
    'staff' => ['uitest.staff', 'staff', 'Staff'],
    'acadoffice' => ['uitest.acadoffice', 'acad_office', 'Acad Office'],
    'acadfaculty' => ['uitest.acadfaculty', 'acad_faculty', 'Acad Faculty'],
];
foreach ($users as [$username, $role]) {
    if ($roleId($role) === null) {
        fwrite(STDERR, "Role '$role' does not exist in sms_db_uitest; stopping without a fallback.\n");
        exit(1);
    }
}

$env = ["# UI-test credentials for sms_db_uitest only. Never commit. Regenerated by tools/uitest/seed-users.php."];
$db->begin_transaction();
foreach ($users as $key => [$username, $role, $label]) {
    $password = rtrim(strtr(base64_encode(random_bytes(18)), '+/', 'Kq'), '=');
    $hash = password_hash($password, PASSWORD_DEFAULT);
    $email = $username . '@uitest.invalid';
    $last = 'UI Test';
    $stmt = $db->prepare(
        'INSERT INTO users (username, email, first_name, last_name, password_hash, is_active, must_change_password)
         VALUES (?, ?, ?, ?, ?, 1, 0)
         ON DUPLICATE KEY UPDATE password_hash = VALUES(password_hash), is_active = 1, must_change_password = 0'
    );
    $stmt->bind_param('sssss', $username, $email, $label, $last, $hash);
    $stmt->execute();
    $stmt = $db->prepare('SELECT id FROM users WHERE username = ?');
    $stmt->bind_param('s', $username);
    $stmt->execute();
    $userId = (int)$stmt->get_result()->fetch_row()[0];
    $stmt = $db->prepare('DELETE FROM user_roles WHERE user_id = ?');
    $stmt->bind_param('i', $userId);
    $stmt->execute();
    $rid = $roleId($role);
    $stmt = $db->prepare('INSERT INTO user_roles (user_id, role_id, assigned_by) VALUES (?, ?, NULL)');
    $stmt->bind_param('ii', $userId, $rid);
    $stmt->execute();
    $upper = strtoupper($key);
    $env[] = "UITEST_{$upper}_USER=$username";
    $env[] = "UITEST_{$upper}_PASS=$password";
    echo "seeded $username ($role)\n";
}
$db->commit();
file_put_contents(__DIR__ . '/../../.env.uitest', implode("\n", $env) . "\n");
echo "credentials written to .env.uitest\n";
require __DIR__ . '/seed-fixtures.php';
